/** `lib/security.ts`: the Worker-layer guard, built from the app's bindings and config. */
export const renderLibSecurity = (app: string): string => `import { env as runtimeEnv } from "cloudflare:workers";
import { createZoneClient } from "@flare/core/security";
import { createSecurity, type BanStore, type MonitorNamespace, type RateLimiter, type Security } from "@flare/core/security/server";
import { getDb } from "../db";
import { securityEvents } from "../db/schema";
import config from "../security.config";

/** Minimal ExecutionContext surface worker/index.ts passes in. */
export interface SecurityContext {
  waitUntil(promise: Promise<unknown>): void;
}

interface SecurityEnv {
  FLARE_SECURITY: BanStore;
  FLARE_SECURITY_MONITOR: MonitorNamespace;
  FLARE_RATE_LIMIT?: RateLimiter;
  /** With both set (wrangler secrets), bans also become zone IP Access Rules. */
  FLARE_SECURITY_ZONE_ID?: string;
  FLARE_SECURITY_API_TOKEN?: string;
}

/** This app's tag on zone rules, so Flare only ever changes its own. */
const APP = ${JSON.stringify(app)};

const bindings = () => runtimeEnv as unknown as SecurityEnv;
let instance: Security | undefined;

/** The app's security layer, one per isolate. */
export function security(): Security {
  const env = bindings();
  instance ??= createSecurity({
    config,
    bans: env.FLARE_SECURITY,
    monitors: env.FLARE_SECURITY_MONITOR,
    rateLimiter: env.FLARE_RATE_LIMIT,
    zone: zoneClient(),
    // Every tripped detector becomes a SecurityEvent row.
    onTrip: (trip) =>
      logSecurityEvent({
        kind: trip.detector.name,
        severity: trip.detector.severity ?? "medium",
        ip: trip.ip,
        path: trip.path,
        userAgent: trip.userAgent,
        count: trip.count,
        banned: trip.banned,
        detail: trip.detector.description ?? null,
      }),
  });
  return instance;
}

/** The zone layer, when this app has a zone and a scoped API token configured. */
export function zoneClient() {
  const env = bindings();
  return env.FLARE_SECURITY_ZONE_ID && env.FLARE_SECURITY_API_TOKEN
    ? createZoneClient({ zoneId: env.FLARE_SECURITY_ZONE_ID, apiToken: env.FLARE_SECURITY_API_TOKEN, app: APP })
    : null;
}

export async function logSecurityEvent(event: typeof securityEvents.$inferInsert): Promise<void> {
  await getDb().insert(securityEvents).values(event);
}

/** Called by worker/index.ts for every request. */
export function protect(request: Request, _env: unknown, ctx: SecurityContext, next: () => Promise<Response>): Promise<Response> {
  return security().protect(request, ctx, next);
}
`;

/** `app/admin/security/actions.ts`: manual ban and unban (admins only). */
export const renderSecurityActions = (): string => `"use server";

import { revalidatePath } from "next/cache";
import { can } from "@flare/core";
import { isIp } from "@flare/core/security";
import { adminSession, policyFor } from "@/lib/admin";
import { logSecurityEvent, security } from "@/lib/security";

/** On failure the submitted values come back, so the form (which React resets) keeps them. */
export type BanResult = { ok: true } | { ok: false; error: string; ip?: string; reason?: string };

const DURATIONS: Record<string, number | null> = { "1h": 3600, "24h": 86_400, "7d": 604_800, permanent: null };

async function adminOnly(): Promise<{ email: string } | { error: string }> {
  const { session, role } = await adminSession();
  if (!session) return { error: "Sign in required." };
  if (!can(policyFor("SecurityEvent"), role, "create")) return { error: "Only admins can ban or unban." };
  return { email: session.user.email };
}

/** Ban an IP at every layer this app has (Worker, and the zone when configured). */
export async function banAction(_previous: BanResult | null, form: FormData): Promise<BanResult> {
  const admin = await adminOnly();
  if ("error" in admin) return { ok: false, error: admin.error };
  const ip = String(form.get("ip") ?? "").trim();
  const reason = String(form.get("reason") ?? "").trim() || "Banned manually";
  const duration = String(form.get("duration") ?? "24h");
  if (!isIp(ip)) return { ok: false, error: \`"\${ip}" isn't an IP address.\`, ip, reason };
  if (!(duration in DURATIONS)) return { ok: false, error: "Choose how long to ban for.", ip, reason };

  try {
    await security().ban(ip, \`\${reason} (by \${admin.email})\`, DURATIONS[duration]!, null);
  } catch (error) {
    return { ok: false, error: \`The ban didn't reach every layer: \${error instanceof Error ? error.message : String(error)}\`, ip, reason };
  }
  await logSecurityEvent({ kind: "manual-ban", severity: "medium", ip, path: "/admin/security", userAgent: null, count: 0, banned: true, detail: \`\${reason} (by \${admin.email})\` });
  revalidatePath("/admin/security");
  return { ok: true };
}

export async function unbanAction(ip: string): Promise<BanResult> {
  const admin = await adminOnly();
  if ("error" in admin) return { ok: false, error: admin.error };
  if (!isIp(ip)) return { ok: false, error: \`"\${ip}" isn't an IP address.\` };
  try {
    await security().unban(ip);
  } catch (error) {
    return { ok: false, error: \`The unban didn't reach every layer: \${error instanceof Error ? error.message : String(error)}\` };
  }
  await logSecurityEvent({ kind: "manual-unban", severity: "low", ip, path: "/admin/security", userAgent: null, count: 0, banned: false, detail: \`by \${admin.email}\` });
  revalidatePath("/admin/security");
  return { ok: true };
}
`;

