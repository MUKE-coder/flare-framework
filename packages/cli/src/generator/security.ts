/** Add the bindings the security layer needs to wrangler.jsonc, keeping everything else. */
export function addSecurityBindings(source: string): { text: string; added: string[] } {
  const config = (parseJsonc(source) ?? {}) as {
    kv_namespaces?: Array<{ binding: string }>;
    durable_objects?: { bindings?: Array<{ name: string }> };
    migrations?: Array<{ tag: string; new_sqlite_classes?: string[]; new_classes?: string[] }>;
    ratelimits?: Array<{ name: string }>;
  };
  let text = source;
  const added: string[] = [];
  const format = { formattingOptions: { insertSpaces: true, tabSize: 2 } };
  const append = (path: (string | number)[], value: unknown) => {
    text = applyEdits(text, modify(text, path, value, { ...format, isArrayInsertion: true }));
  };

  if (!config.kv_namespaces?.some((entry) => entry.binding === "FLARE_SECURITY")) {
    if (config.kv_namespaces) append(["kv_namespaces", config.kv_namespaces.length], { binding: "FLARE_SECURITY" });
    else text = applyEdits(text, modify(text, ["kv_namespaces"], [{ binding: "FLARE_SECURITY" }], format));
    added.push("kv_namespaces: FLARE_SECURITY (ban list)");
  }
  if (!config.durable_objects?.bindings?.some((entry) => entry.name === "FLARE_SECURITY_MONITOR")) {
    const binding = { name: "FLARE_SECURITY_MONITOR", class_name: "SecurityMonitor" };
    if (config.durable_objects?.bindings) append(["durable_objects", "bindings", config.durable_objects.bindings.length], binding);
    else text = applyEdits(text, modify(text, ["durable_objects", "bindings"], [binding], format));
    added.push("durable_objects: FLARE_SECURITY_MONITOR (per-IP counters)");
  }
  const classes = (config.migrations ?? []).flatMap((migration) => [...(migration.new_sqlite_classes ?? []), ...(migration.new_classes ?? [])]);
  if (!classes.includes("SecurityMonitor")) {
    const migration = { tag: "flare-security-v1", new_sqlite_classes: ["SecurityMonitor"] };
    if (config.migrations) append(["migrations", config.migrations.length], migration);
    else text = applyEdits(text, modify(text, ["migrations"], [migration], format));
    added.push("migrations: SecurityMonitor");
  }
  if (!config.ratelimits?.some((entry) => entry.name === "FLARE_RATE_LIMIT")) {
    // namespace_id is any number unique within the account; a random one avoids clashing with other apps.
    const binding = { name: "FLARE_RATE_LIMIT", namespace_id: String(1000 + Math.floor(Math.random() * 9000)), simple: { limit: 120, period: 60 } };
    if (config.ratelimits) append(["ratelimits", config.ratelimits.length], binding);
    else text = applyEdits(text, modify(text, ["ratelimits"], [binding], format));
    added.push("ratelimits: FLARE_RATE_LIMIT (120 requests/minute per IP on /api)");
  }
  return { text, added };
}

