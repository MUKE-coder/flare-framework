export interface PlannedFile {
  /** Relative to the app root. */
  path: string;
  content?: string;
  header?: string;
  /**
   * An edit to a file the app owns, rather than a file Flare writes whole.
   *
   * Used where Flare has to put something inside a file that is not its own —
   * `prisma/schema/base.prisma`, which holds the datasource and Better Auth's tables and
   * is never regenerated, but which needs the other half of every `belongsTo("User")`
   * relation. The transform gets the current contents and returns the new ones, or null
   * if it cannot make the edit safely; returning the input unchanged means "nothing to
   * do". A file that does not exist is skipped, not created.
   */
  transform?: (existing: string) => string | null;
}

export const resourceHeader = (name: string) =>
  `// Generated by \`flare gen resource ${name}\`. Code inside the generated block is\n` +
  `// rewritten on regeneration; add your own code outside it.\n`;

const HEADER_PATTERN = /^\/\/ Generated by `flare gen resource (\w+)`/;

/** Every derived file for every resource, plus the shared relations, registry, and schema index. */
export function planFiles(all: LoadedResource[], policies?: LoadedPolicy[], stack: Stack = "cloudflare"): PlannedFile[] {
  const files: PlannedFile[] = [];
  for (const entry of all) {
    for (const file of resourceFiles(entry, all, stack)) files.push({ ...file, header: resourceHeader(entry.resource.name) });
  }
  files.push({
    path: "resources/index.ts",
    content: renderRegistry(all),
    header: "// Registry of every resource descriptor (maintained by flare gen).\n",
  });

  if (stack === "next") {
    files.push(
      // Prisma keeps every model in one schema and writes its own migrations, so there
      // is no per-table module and no relations file to maintain.
      {
        path: "prisma/schema/resources.prisma",
        content: renderPrismaSchema(all),
        header: "// Generated from the descriptors in resources/. Edit a descriptor, not this.\n",
      },
      {
        path: "resources/server.ts",
        content: renderPrismaServerRegistry(all),
        header: "// Server-only: resource name → descriptor and Prisma delegate (maintained by flare gen).\n",
      },
      {
        // Not a file Flare writes: base.prisma is the app's. Only the back-references for
        // belongsTo("User") go in, in a block inside model User, because Prisma refuses a
        // relation with one side missing and that side is on a model Flare never generates.
        path: "prisma/schema/base.prisma",
        transform: (existing) => withAuthUserBackReferences(existing, authUserBackReferences(all)),
      },
    );
  } else {
    files.push(
      { path: "db/relations.ts", content: renderRelations(all), header: "// Drizzle relations for every resource (maintained by flare gen).\n" },
      {
        path: "resources/server.ts",
        content: renderServerRegistry(all),
        header: "// Server-only: resource name → descriptor and table (maintained by flare gen).\n",
      },
      { path: "db/schema.ts", content: renderSchemaIndex(all) },
    );
  }
  // The picker's endpoint for belongsTo("User"), generated only for apps that have such
  // a field — see users-route.ts for who is allowed to see whom.
  if (usesAuthUser(all)) {
    const header = `// Read-only accounts endpoint for belongsTo("User") pickers (maintained by flare gen).\n`;
    files.push(
      { path: "app/api/users/route.ts", content: renderUsersRoute(stack), header },
      { path: "app/api/users/[id]/route.ts", content: renderUserItemRoute(stack), header },
    );
  }

  // Only when the caller loaded policies: commands that don't (`gen resource`) leave the registry alone.
  if (policies) {
    files.push({
      path: "policies/index.ts",
      content: renderPolicyRegistry(policies),
      header: "// Registry of every resource policy (maintained by flare gen policy).\n",
    });
  }
  return files;
}

export type Outcome = "create" | "update" | "identical" | "skipped-drift" | "skipped-unmarked";

export interface FileResult {
  path: string;
  status: FileStatus;
  outcome: Outcome;
}

/** Inspect (dryRun) or write planned files. Drifted and hand-written files are skipped, never thrown. */
export function applyPlan(appRoot: string, plan: PlannedFile[], options: { force?: boolean; dryRun?: boolean } = {}): FileResult[] {
  return plan.map(({ path, content, header, transform }) => {
    const absolute = join(appRoot, path);
    if (transform) {
      // A file the app owns: never created, never reformatted, and left alone entirely
      // if the edit cannot be placed.
      if (!existsSync(absolute)) return { path, status: "missing", outcome: "skipped-unmarked" };
      const existing = readFileSync(absolute, "utf8");
      const next = transform(existing);
      if (next === null) return { path, status: "unmarked", outcome: "skipped-unmarked" };
      if (next === existing) return { path, status: "identical", outcome: "identical" };
      if (!options.dryRun) writeFileSync(absolute, next);
      return { path, status: "outdated", outcome: "update" };
    }
    const status = inspectGenerated(absolute, content!);
    if (status === "unmarked") return { path, status, outcome: "skipped-unmarked" };
    if (status === "drift" && !options.force) return { path, status, outcome: "skipped-drift" };
    if (options.dryRun) {
      const outcome = status === "missing" ? "create" : status === "identical" ? "identical" : "update";
      return { path, status, outcome };
    }
    try {
      return { path, status, outcome: writeGenerated(absolute, content!, { header, force: options.force }) };
    } catch (error) {
      if (error instanceof DriftError) return { path, status: "drift", outcome: "skipped-drift" };
      throw error;
    }
  });
}

/**
 * Resource-owned generated files (found by their header) that the current plan no longer
 * produces: the resource was deleted, or its table/slug was renamed.
 */
export function findOrphans(appRoot: string, all: LoadedResource[]): { path: string; resource: string }[] {
  const planned = new Set(planFiles(all).map((file) => file.path));
  const candidates: string[] = [];
  const list = (dir: string, match: (name: string) => boolean) =>
    existsSync(join(appRoot, dir)) ? readdirSync(join(appRoot, dir)).filter(match).map((name) => `${dir}/${name}`) : [];

  candidates.push(...list("db/schema", (name) => name.endsWith(".ts")));
  candidates.push(...list("resources", (name) => /\.(client|validators)\.ts$/.test(name)));
  for (const dir of list("app/api", () => true)) {
    for (const file of [`${dir}/route.ts`, `${dir}/[id]/route.ts`]) if (existsSync(join(appRoot, file))) candidates.push(file);
  }
  for (const dir of list("app/dashboard", () => true)) {
    // Every file `resourceFiles` writes under app/dashboard, so a resource whose
    // descriptor is already gone leaves nothing behind — its skeletons included.
    const pages = [`${dir}/page.tsx`, `${dir}/new/page.tsx`, `${dir}/[id]/page.tsx`, `${dir}/[id]/edit/page.tsx`];
    const skeletons = [`${dir}/loading.tsx`, `${dir}/new/loading.tsx`, `${dir}/[id]/loading.tsx`, `${dir}/[id]/edit/loading.tsx`];
    for (const file of [...pages, ...skeletons]) {
      if (existsSync(join(appRoot, file))) candidates.push(file);
    }
  }

  const orphans: { path: string; resource: string }[] = [];
  for (const path of candidates) {
    const match = HEADER_PATTERN.exec(readFileSync(join(appRoot, path), "utf8"));
    if (match && !planned.has(path)) orphans.push({ path, resource: match[1]! });
  }
  return orphans;
}

/** Files every app needs once resources exist (copied from the app template if missing). */
export function ensureSupportFiles(appRoot: string, log: (message: string) => void) {
  const stack = readStack(appRoot);
  // The engine a generated route imports. An app made before it moved out of the
  // package doesn't have these, and its next `gen resource` would write routes
  // importing a folder that isn't there — so they are installed on demand.
  const engine = ["rows.ts", "query.ts", "http.ts", "store.ts", "handlers.ts", "index.ts", stack === "next" ? "prisma-rows.ts" : "drizzle-rows.ts"].map(
    (name) => `lib/resource/${name}`,
  );

  // user-titles.ts is in the list rather than conditional on a belongsTo("User") field:
  // the three admin components import it unconditionally, so an app missing it would
  // fail to build the moment one of them is regenerated.
  for (const path of ["lib/api.ts", "lib/cache.ts", "lib/user-titles.ts", ...engine]) {
    const target = join(appRoot, path);
    if (existsSync(target)) continue;
    // The Next.js overlay wins where it has its own version of a file.
    const source = [join(templatesDir, "next", path), join(templatesDir, "app", path)].find(
      (candidate) => (stack === "next" || !candidate.includes(`${sep}next${sep}`)) && existsSync(candidate),
    );
    if (!source) continue;
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(source, target);
    log(`${pc.green("create".padEnd(9))} ${path}`);
  }
}

export function logResults(results: FileResult[], log: (message: string) => void, options: { showIdentical?: boolean } = {}) {
  for (const { path, outcome } of results) {
    if (outcome === "identical" && !options.showIdentical) continue;
    const label =
      outcome === "create"
        ? pc.green("create")
        : outcome === "update"
          ? pc.yellow("update")
          : outcome === "identical"
            ? pc.dim("identical")
            : pc.red(outcome === "skipped-drift" ? "drift" : "hand-written");
    log(`${label.padEnd(18)} ${path}`);
  }
}
