/** `app/api/billing/checkout/route.ts`: start Checkout for a new subscription or a one-time purchase. */
export const renderCheckoutRoute = (): string => `import { NextRequest, NextResponse } from "next/server";
import { eq } from "drizzle-orm";
import { isLiveSubscription, randomLetters } from "@flare/core";
import { getDb } from "@/db";
import { plans } from "@/db/schema";
import { getSession } from "@/lib/session";
import { appOrigin, createStripe, getOrCreateCustomer } from "@/lib/stripe";

/**
 * POST { planSlug }. The plan decides the mode: a recurring price starts a
 * subscription, a one-time price a payment. Prices only ever come from the Plan
 * table, so a client can't pay for an arbitrary price. A customer who already has
 * a subscription changes plans through the portal instead of buying a second one.
 */
export async function POST(request: NextRequest) {
  const raw = await request.text();
  const session = await getSession();
  if (!session) return NextResponse.json({ error: "Sign in to check out." }, { status: 401 });

  let planSlug = "";
  try {
    planSlug = String((JSON.parse(raw) as { planSlug?: unknown }).planSlug ?? "");
  } catch {
    return NextResponse.json({ error: "Send JSON like {\\"planSlug\\": \\"pro\\"}." }, { status: 400 });
  }
  const plan = planSlug ? await getDb().select().from(plans).where(eq(plans.slug, planSlug)).get() : undefined;
  if (!plan || plan.active === false) return NextResponse.json({ error: "That plan isn't available." }, { status: 404 });

  const mode = plan.interval ? "subscription" : "payment";
  const customer = await getOrCreateCustomer(session.user);
  if (mode === "subscription" && isLiveSubscription(customer.subscriptionStatus)) {
    return NextResponse.json({ error: "You already have a subscription. Change plans from the billing page." }, { status: 409 });
  }

  const base = appOrigin(request);
  const checkout = await createStripe().checkout.sessions.create({
    mode,
    line_items: [{ price: plan.stripePriceId, quantity: 1 }],
    customer: customer.stripeCustomerId,
    client_reference_id: customer.id,
    integration_identifier: \`flare-billing-\${randomLetters()}\`,
    success_url: \`\${base}/dashboard/billing?checkout=success&session_id={CHECKOUT_SESSION_ID}\`,
    cancel_url: \`\${base}/dashboard/billing?checkout=cancelled\`,
  });
  if (!checkout.url) return NextResponse.json({ error: "Stripe did not return a checkout URL." }, { status: 502 });
  return NextResponse.json({ url: checkout.url });
}
`;

/** `app/api/billing/portal/route.ts`: the Stripe Customer Portal, optionally straight to a plan change. */
export const renderPortalRoute = (): string => `import { NextRequest, NextResponse } from "next/server";
import { eq } from "drizzle-orm";
import { isLiveSubscription } from "@flare/core";
import { getDb } from "@/db";
import { plans } from "@/db/schema";
import { getSession } from "@/lib/session";
import { appOrigin, billingPortalConfiguration, createStripe, getOrCreateCustomer } from "@/lib/stripe";

/**
 * POST {} opens the portal (payment methods, invoices, cancel). POST { planSlug }
 * opens its plan-change confirmation for that plan: Stripe shows the prorated
 * amount and applies the change to the existing subscription, so switching plans
 * never starts a second one.
 */
export async function POST(request: NextRequest) {
  const raw = await request.text();
  const session = await getSession();
  if (!session) return NextResponse.json({ error: "Sign in to manage billing." }, { status: 401 });

  let planSlug = "";
  try {
    planSlug = raw ? String((JSON.parse(raw) as { planSlug?: unknown }).planSlug ?? "") : "";
  } catch {
    return NextResponse.json({ error: "Send JSON like {\\"planSlug\\": \\"pro\\"}, or no body." }, { status: 400 });
  }

  const customer = await getOrCreateCustomer(session.user);
  const stripe = createStripe();
  const returnUrl = \`\${appOrigin(request)}/dashboard/billing\`;

  const configuration = await billingPortalConfiguration(stripe);

  if (!planSlug) {
    const portal = await stripe.billingPortal.sessions.create({ customer: customer.stripeCustomerId, return_url: returnUrl, configuration });
    return NextResponse.json({ url: portal.url });
  }

  const plan = await getDb().select().from(plans).where(eq(plans.slug, planSlug)).get();
  if (!plan || plan.active === false || !plan.interval) return NextResponse.json({ error: "That plan isn't available." }, { status: 404 });
  if (!customer.stripeSubscriptionId || !isLiveSubscription(customer.subscriptionStatus)) {
    return NextResponse.json({ error: "You don't have a subscription to change yet. Subscribe first." }, { status: 409 });
  }
  const subscription = await stripe.subscriptions.retrieve(customer.stripeSubscriptionId);
  const item = subscription.items.data[0];
  if (!item) return NextResponse.json({ error: "The subscription has no items to change." }, { status: 409 });

  const portal = await stripe.billingPortal.sessions.create({
    customer: customer.stripeCustomerId,
    return_url: returnUrl,
    configuration,
    flow_data: {
      type: "subscription_update_confirm",
      subscription_update_confirm: {
        subscription: subscription.id,
        items: [{ id: item.id, price: plan.stripePriceId, quantity: 1 }],
      },
      after_completion: { type: "redirect", redirect: { return_url: \`\${returnUrl}?changed=1\` } },
    },
  });
  return NextResponse.json({ url: portal.url });
}
`;

/** `app/api/webhooks/stripe/route.ts`: signature-verified events that keep billing state in sync. */
export const renderWebhookRoute = (): string => `import { NextRequest, NextResponse } from "next/server";
import Stripe from "stripe";
import { createStripe, failCheckoutSession, invoiceSubscriptionId, stripeSecrets, syncCheckoutSession, syncSubscription } from "@/lib/stripe";

/**
 * Stripe calls this, so it has no session: the signature is the authentication.
 * Point a webhook endpoint at /api/webhooks/stripe with these events:
 *   checkout.session.completed, checkout.session.async_payment_succeeded,
 *   checkout.session.async_payment_failed, customer.subscription.created,
 *   customer.subscription.updated, customer.subscription.deleted,
 *   customer.subscription.paused, customer.subscription.resumed,
 *   invoice.paid, invoice.payment_failed
 */
export async function POST(request: NextRequest) {
  // The raw body: the signature covers these exact bytes.
  const payload = await request.text();
  const { STRIPE_WEBHOOK_SECRET } = stripeSecrets();
  if (!STRIPE_WEBHOOK_SECRET) {
    return NextResponse.json({ error: "STRIPE_WEBHOOK_SECRET is not set." }, { status: 501 });
  }
  const signature = request.headers.get("stripe-signature");
  if (!signature) return NextResponse.json({ error: "Missing stripe-signature header." }, { status: 400 });

  let event: Stripe.Event;
  try {
    // Workers only offer async (SubtleCrypto) HMAC, so the async variant is required here.
    event = await createStripe().webhooks.constructEventAsync(payload, signature, STRIPE_WEBHOOK_SECRET, undefined, Stripe.createSubtleCryptoProvider());
  } catch {
    return NextResponse.json({ error: "Invalid signature." }, { status: 400 });
  }

  // Each handler re-fetches the object from Stripe, so duplicates and
  // out-of-order deliveries are harmless. A thrown error returns 500 and Stripe retries.
  switch (event.type) {
    case "checkout.session.completed":
    case "checkout.session.async_payment_succeeded":
      await syncCheckoutSession(event.data.object.id);
      break;
    case "checkout.session.async_payment_failed":
      await failCheckoutSession(event.data.object.id);
      break;
    case "customer.subscription.created":
    case "customer.subscription.updated":
    case "customer.subscription.deleted":
    case "customer.subscription.paused":
    case "customer.subscription.resumed":
      await syncSubscription(event.data.object.id);
      break;
    case "invoice.paid":
    case "invoice.payment_failed": {
      const subscriptionId = invoiceSubscriptionId(event.data.object);
      if (subscriptionId) await syncSubscription(subscriptionId);
      break;
    }
  }
  return NextResponse.json({ received: true });
}
`;

/** `components/billing/billing-button.tsx`: POST to a billing route and follow the Stripe URL it returns. */
export const renderBillingButton = (): string => `"use client";

import { useState } from "react";
import { Button } from "@/components/ui/button";
import { Spinner } from "@/components/ui/spinner";

/**
 * Starts a Stripe flow: Checkout (\`/api/billing/checkout\`) or the portal
 * (\`/api/billing/portal\`), optionally for one plan. Errors show under the button.
 */
export function BillingButton({
  endpoint,
  planSlug,
  variant = "default",
  children,
}: {
  endpoint: "/api/billing/checkout" | "/api/billing/portal";
  planSlug?: string;
  variant?: "default" | "outline" | "secondary";
  children: React.ReactNode;
}) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function start() {
    setBusy(true);
    setError(null);
    try {
      const response = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(planSlug ? { planSlug } : {}),
      });
      const data = (await response.json().catch(() => null)) as { url?: string; error?: string } | null;
      if (!response.ok || !data?.url) {
        setError(data?.error ?? "Stripe could not be reached. Try again in a moment.");
        setBusy(false);
        return;
      }
      window.location.assign(data.url);
    } catch {
      setError("Stripe could not be reached. Try again in a moment.");
      setBusy(false);
    }
  }

  return (
    <div className="flex flex-col items-start gap-2">
      <Button onClick={start} disabled={busy} variant={variant}>
        {busy && <Spinner data-icon="inline-start" />}
        {children}
      </Button>
      {error && (
        <p role="alert" className="text-sm text-destructive">
          {error}
        </p>
      )}
    </div>
  );
}
`;

