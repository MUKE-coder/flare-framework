/**
 * `flare gen billing` scaffolding (Stripe).
 *
 * Three regular Flare resources carry the data:
 *
 *   Plan     – one row per Stripe Price. Recurring prices are subscription plans;
 *              one-time prices are things to buy once. `flare billing:sync-plans`
 *              mirrors them from Stripe.
 *   Customer – who pays. A signed-in user checks out, and the webhook keeps this
 *              row's subscription state in sync ("Subscription fields on Customer").
 *   Purchase – one row per paid one-time Checkout.
 *
 * The rules that decide subscription state live in `@flare/core` (billing.ts) and
 * are unit-tested there; the files generated here are the Stripe and database glue.
 */

export const BILLING_PROVIDER = "stripe" as const;
export const BILLING_MODES = ["subscriptions"] as const;

export function validateBillingOptions(provider: string | undefined, mode: string | undefined) {
  if (provider && provider !== BILLING_PROVIDER) {
    throw new Error(`--provider "${provider}" is not supported yet. Supported: ${BILLING_PROVIDER}.`);
  }
  if (mode && !(BILLING_MODES as readonly string[]).includes(mode)) {
    throw new Error(`--mode "${mode}" is not supported. Supported: ${BILLING_MODES.join(", ")} (it includes one-time checkout too).`);
  }
}

/** Plan: one row per Stripe Price. `interval` is empty for one-time prices. */
export const PLAN_FIELDS =
  "name:string, slug:string!, description:text?, stripeProductId:string?, stripePriceId:string!, " +
  "amount:int, currency:string, interval:enum(month,year)?, active:boolean?, sort:int?";

/** The subscription fields every Customer needs, merged into an existing Customer too. */
export const CUSTOMER_FIELDS =
  "name:string, email:string!, userId:string!?, stripeCustomerId:string!?, stripeSubscriptionId:string?, " +
  "subscriptionStatus:enum(none,incomplete,trialing,active,past_due,paused,canceled,unpaid)?, " +
  "subscriptionEndsAt:datetime?, cancelAtPeriodEnd:boolean?, planId:belongsTo(Plan)?";

/** Purchase: one row per one-time Checkout, keyed by its session so webhooks are idempotent. */
export const PURCHASE_FIELDS =
  "customerId:belongsTo(Customer), planId:belongsTo(Plan)?, stripeCheckoutSessionId:string!, " +
  "amount:int, currency:string, status:enum(pending,paid,failed)";

export const BILLING_RESOURCES = {
  Plan: PLAN_FIELDS,
  Customer: CUSTOMER_FIELDS,
  Purchase: PURCHASE_FIELDS,
} as const;
export type BillingResource = keyof typeof BILLING_RESOURCES;

export const billingFields = (name: BillingResource): ParsedField[] => parseFields(BILLING_RESOURCES[name]);

export const renderBillingDescriptor = (name: BillingResource): string => renderDescriptor(name, billingFields(name));

/**
 * Add the billing fields an existing descriptor's tracked block is missing, keeping
 * every field it already has. Returns null when nothing is missing.
 */
export function mergeBillingFields(name: BillingResource, block: string): string | null {
  const present = new Set([...block.matchAll(/^\s*(\w+)\s*:/gm)].map((match) => match[1]));
  const missing = billingFields(name).filter((field) => !present.has(field.key));
  if (missing.length === 0) return null;
  const lines = missing.map((field) => `${renderField(field)}\n`).join("");
  return `${block.replace(/\s*$/, "\n")}${lines}`;
}

